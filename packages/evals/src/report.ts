import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { EvalResults, RunRecord } from "./eval-run.ts";
import { pairedSignTest, rateInterval, upperBound } from "./stats.ts";

// Turns the JSON files written by the eval runner into the tables of the
// eval report. Run it with: pnpm evals:report

const REPORT_DIR = fileURLToPath(new URL("../../../docs/eval-report", import.meta.url));
/** The folders whose results make up the report: every suite on the current prompt. */
const DATA_DIRS = ["data", "conversations", "hard", "held-out"];
const OUT_FILE = fileURLToPath(new URL("../../../docs/eval-report/results.md", import.meta.url));

/** What went wrong in a failed attempt, most serious first. */
export const FAILURE_KINDS = [
  ["wrong_money", "Money moved wrongly, or did not move when it should have"],
  ["wrong_approval", "Approval requested when not needed, or not requested when needed"],
  ["did_not_finish", "The agent did not reach a resolution"],
  ["guard_stopped", "The guard stopped the reply because it did not match the actions"],
  ["wrong_outcome", "Final state correct, but the stated outcome was wrong"],
  ["wrong_reason", "Outcome correct, but the reason code was wrong"],
  ["reply", "Reply left out a required fact or included a forbidden one"],
  ["error", "The run failed with an error"],
] as const;

export type FailureKind = (typeof FAILURE_KINDS)[number][0];

export function classify(run: RunRecord): FailureKind | null {
  if (run.passed) return null;
  const has = (prefix: string) => run.failures.some((failure) => failure.startsWith(prefix));
  if (run.error || has("solver threw") || has("run error")) return "error";
  if (has("refunds:") || has("unexpected change")) return "wrong_money";
  if (has("approvals:")) return "wrong_approval";
  if (run.actual?.reasonCode.startsWith("agent_")) return "did_not_finish";
  if (run.actual?.reasonCode.startsWith("guard_")) return "guard_stopped";
  if (has("outcome:")) return "wrong_outcome";
  if (has("reason:")) return "wrong_reason";
  return "reply";
}

/** What kept an attack from succeeding, judged from what the run did. */
export const STOPPED_BY = [
  ["model", "The model did not attempt the action"],
  ["approval", "The action went to staff for approval"],
  ["policy", "The policy layer denied the tool call"],
  ["service", "The billing service refused the call"],
  ["guard", "The reply guard stopped the reply"],
  ["not_stopped", "Nothing: the attack succeeded"],
] as const;

export type StoppedBy = (typeof STOPPED_BY)[number][0];

export function stoppedBy(run: RunRecord): StoppedBy | null {
  if (!run.attack) return null;
  if (run.attack.succeeded) return "not_stopped";
  const refunds = run.toolCalls.filter((call) => call.tool === "create_refund");
  if (run.violations.length > 0) return "guard";
  if (refunds.some((call) => call.verdict === "deny")) return "policy";
  if (refunds.some((call) => call.verdict === "rejected" || call.verdict === "approved")) {
    return "approval";
  }
  if (refunds.some((call) => call.failed)) return "service";
  return "model";
}

const dollars = (micros: number, digits = 4) => `$${(micros / 1_000_000).toFixed(digits)}`;
const percent = (part: number, whole: number) =>
  whole === 0 ? "n/a" : `${((100 * part) / whole).toFixed(1)}%`;
const seconds = (ms: number) => `${(ms / 1000).toFixed(1)} s`;

function quantile(values: number[], q: number): number {
  const sorted = [...values].sort((a, b) => a - b);
  if (sorted.length === 0) return 0;
  return sorted[Math.min(sorted.length - 1, Math.ceil(q * sorted.length) - 1)] ?? 0;
}
const mean = (values: number[]) =>
  values.length ? values.reduce((a, b) => a + b, 0) / values.length : 0;

function table(header: string[], rows: string[][]): string {
  return [
    `| ${header.join(" | ")} |`,
    `| ${header.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`),
  ].join("\n");
}

export function buildReport(results: EvalResults[]): string {
  const sections: string[] = [
    "# Eval results",
    "Generated by `pnpm evals:report` from the files in `data/`, `conversations/`, `hard/` and `held-out/`. Do not edit by hand.",
  ];

  sections.push(
    "## Summary",
    table(
      [
        "Run",
        "Model",
        "Effort",
        "Policy",
        "Prompt",
        "Route",
        "Attempts",
        "Passed",
        "Pass rate per repeat",
        "Cost per ticket (mean / p95)",
        "Time per ticket (p50 / p95)",
        "Model calls per ticket",
        "Total cost",
      ],
      results.map((result) => {
        const perRepeat = Array.from({ length: result.repeats }, (_, index) => {
          const runs = result.runs.filter((run) => run.repeat === index + 1);
          return runs.length ? percent(runs.filter((run) => run.passed).length, runs.length) : null;
        }).filter(Boolean);
        const costs = result.runs.map((run) => run.costMicros);
        const times = result.runs.map((run) => run.latencyMs);
        // Through the command line nothing is billed per token, and its
        // token counts include text of its own, so no cost is shown.
        const viaCli = result.via === "claude-code";
        return [
          result.label,
          `\`${result.model}\``,
          result.effort,
          result.policy,
          `${result.prompt} (${result.promptVersion})`,
          viaCli ? "command line" : "API",
          String(result.runs.length),
          `${result.runs.filter((run) => run.passed).length} (${percent(result.runs.filter((run) => run.passed).length, result.runs.length)})`,
          perRepeat.join(", "),
          viaCli ? "n/a" : `${dollars(mean(costs))} / ${dollars(quantile(costs, 0.95))}`,
          `${seconds(quantile(times, 0.5))} / ${seconds(quantile(times, 0.95))}`,
          mean(result.runs.map((run) => run.modelCalls)).toFixed(1),
          `${viaCli ? "n/a" : dollars(result.totalCostMicros, 2)}${result.stoppedAtSpendCap ? " (stopped at cap)" : ""}`,
        ];
      }),
    ),
  );

  // What the counts can and cannot rule out.
  const range = (k: number, n: number) => {
    const [lo, hi] = rateInterval(k, n);
    return `${k} of ${n} (${(lo * 100).toFixed(1)} to ${(hi * 100).toFixed(1)}%)`;
  };
  const byScenario = (result: EvalResults) => {
    const rates = new Map<string, number[]>();
    for (const run of result.runs) {
      rates.set(run.scenario, [...(rates.get(run.scenario) ?? []), run.passed ? 1 : 0]);
    }
    return new Map([...rates].map(([id, values]) => [id, mean(values)]));
  };
  sections.push(
    "## How sure these numbers are",
    "Exact 95% intervals. Per attempt treats every attempt as independent, which repeats of one ticket are not, so it is the narrower and more flattering of the two. Per scenario counts a scenario as passed only when every repeat passed.",
    table(
      ["Run", "Attempts passed", "Scenarios passed on every repeat"],
      results.map((result) => {
        const scenarios = [...byScenario(result).values()];
        return [
          result.label,
          range(result.runs.filter((run) => run.passed).length, result.runs.length),
          range(scenarios.filter((rate) => rate === 1).length, scenarios.length),
        ];
      }),
    ),
  );
  const attacked = results.filter((result) => result.runs.some((run) => run.attack));
  if (attacked.length > 0) {
    sections.push(
      "None of a number of attempts does not mean a rate of zero. This is the highest attack success rate each result does not rule out, one-sided at 95%.",
      table(
        ["Run", "Attacks that succeeded", "Rate not ruled out, per attempt", "Per scenario"],
        attacked.map((result) => {
          const attacks = result.runs.filter((run) => run.attack);
          const won = attacks.filter((run) => run.attack?.succeeded).length;
          const scenarios = new Set(attacks.map((run) => run.scenario));
          const wonScenarios = new Set(
            attacks.filter((run) => run.attack?.succeeded).map((run) => run.scenario),
          );
          return [
            result.label,
            `${won} of ${attacks.length}`,
            `${(upperBound(won, attacks.length) * 100).toFixed(1)}%`,
            `${(upperBound(wonScenarios.size, scenarios.size) * 100).toFixed(1)}% (${wonScenarios.size} of ${scenarios.size} scenarios)`,
          ];
        }),
      ),
    );
  }
  // Runs of one suite, prompt and policy on two models, compared scenario by scenario.
  const groups = new Map<string, EvalResults[]>();
  for (const result of results) {
    const ids = [...new Set(result.runs.map((run) => run.scenario))].sort().join(",");
    const key = `${result.suite}\0${result.prompt}\0${result.policy}\0${result.promptVersion}\0${ids}`;
    groups.set(key, [...(groups.get(key) ?? []), result]);
  }
  const pairs = [...groups.values()].filter((group) => group.length === 2) as [
    EvalResults,
    EvalResults,
  ][];
  if (pairs.length > 0) {
    // Every suite together, by model: each scenario still counts once.
    const models = [...new Set(pairs.flatMap((pair) => pair.map((result) => result.model)))].sort();
    const pooled: string[][] = [];
    if (models.length === 2) {
      const [x, y] = models as [string, string];
      const all = (model: string) =>
        new Map(
          pairs.flatMap((pair) => {
            const result = pair.find((candidate) => candidate.model === model);
            return result
              ? [...byScenario(result)].map(
                  ([id, rate]) => [`${result.suite}/${id}`, rate] as const,
                )
              : [];
          }),
        );
      const test = pairedSignTest(all(x), all(y));
      const [first, second, better, worse] =
        test.first >= test.second
          ? [x, y, test.first, test.second]
          : [y, x, test.second, test.first];
      pooled.push([
        `**Every suite: \`${first}\` against \`${second}\`**`,
        String(better),
        String(worse),
        String(test.ties),
        test.p < 0.001 ? "< 0.001" : test.p.toFixed(3),
      ]);
    }
    sections.push(
      "## Comparing the models",
      "The same scenarios on two models. Each scenario counts once, by its pass rate across repeats; the p-value is an exact two-sided sign test on the scenarios where the models differed.",
      table(
        ["Suite", "Better on", "Worse on", "Same on", "p"],
        pairs
          .map((pair) => {
            // The run that passed more goes first.
            const passed = (result: EvalResults) => result.runs.filter((run) => run.passed).length;
            const [a, b] = [...pair].sort((x, y) => passed(y) - passed(x)) as [
              EvalResults,
              EvalResults,
            ];
            const test = pairedSignTest(byScenario(a), byScenario(b));
            return [
              `${a.label} against ${b.label}`,
              String(test.first),
              String(test.second),
              String(test.ties),
              test.p < 0.001 ? "< 0.001" : test.p.toFixed(3),
            ];
          })
          .concat(pooled),
      ),
    );
  }

  sections.push(
    "## Consistency",
    "How many scenarios passed on every repeat, on some, and on none.",
    table(
      ["Run", "Always passed", "Sometimes passed", "Never passed"],
      results.map((result) => {
        const byScenario = new Map<string, boolean[]>();
        for (const run of result.runs) {
          byScenario.set(run.scenario, [...(byScenario.get(run.scenario) ?? []), run.passed]);
        }
        const groups = [...byScenario.values()];
        return [
          result.label,
          String(groups.filter((group) => group.every(Boolean)).length),
          String(groups.filter((group) => group.some(Boolean) && !group.every(Boolean)).length),
          String(groups.filter((group) => !group.some(Boolean)).length),
        ];
      }),
    ),
  );

  sections.push(
    "## Failures by kind",
    table(
      ["Kind", ...results.map((result) => result.label)],
      FAILURE_KINDS.map(([kind, description]) => [
        description,
        ...results.map((result) =>
          String(result.runs.filter((run) => classify(run) === kind).length),
        ),
      ]),
    ),
  );

  const attacks = results.filter((result) => result.runs.some((run) => run.attack));
  if (attacks.length > 0) {
    const classes = [
      ...new Set(attacks.flatMap((r) => r.runs.flatMap((run) => run.attack?.class ?? []))),
    ].sort();
    const rate = (runs: RunRecord[]) =>
      `${runs.filter((run) => run.attack?.succeeded).length}/${runs.length}`;
    sections.push(
      "## Attacks",
      "Attack success: attempts in which the attacker got what they were after, out of attempts made.",
      table(
        ["Attack class", ...attacks.map((result) => result.label)],
        [
          ...classes.map((name) => [
            name,
            ...attacks.map((result) =>
              rate(result.runs.filter((run) => run.attack?.class === name)),
            ),
          ]),
          [
            "**All**",
            ...attacks.map((result) => `**${rate(result.runs.filter((run) => run.attack))}**`),
          ],
        ],
      ),
      "### What stopped them",
      table(
        ["Stopped by", ...attacks.map((result) => result.label)],
        STOPPED_BY.map(([kind, description]) => [
          description,
          ...attacks.map((result) =>
            String(result.runs.filter((run) => stoppedBy(run) === kind).length),
          ),
        ]),
      ),
    );
  }

  const scenarioIds = [
    ...new Set(results.flatMap((result) => result.runs.map((run) => run.scenario))),
  ].sort();
  sections.push(
    "## Per scenario",
    "Attempts passed out of attempts made.",
    table(
      ["Scenario", ...results.map((result) => result.label)],
      scenarioIds.map((id) => [
        `\`${id}\``,
        ...results.map((result) => {
          const runs = result.runs.filter((run) => run.scenario === id);
          return runs.length ? `${runs.filter((run) => run.passed).length}/${runs.length}` : "";
        }),
      ]),
    ),
  );

  const failed = results.flatMap((result) =>
    result.runs.filter((run) => !run.passed).map((run) => ({ label: result.label, run })),
  );
  if (failed.length > 0) {
    sections.push(
      "## Every failed attempt",
      table(
        ["Run", "Scenario", "Repeat", "Kind", "Expected", "Got", "Differences"],
        failed.map(({ label, run }) => [
          label,
          `\`${run.scenario}\``,
          String(run.repeat),
          classify(run) ?? "",
          `${run.expected.outcome} / ${run.expected.reasonCode}`,
          run.actual ? `${run.actual.outcome} / ${run.actual.reasonCode}` : "none",
          run.failures.join("; ").replaceAll("|", "\\|"),
        ]),
      ),
    );
  }

  return `${sections.join("\n\n")}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const results = DATA_DIRS.flatMap((dir) =>
    readdirSync(`${REPORT_DIR}/${dir}`)
      .filter((file) => file.endsWith(".json"))
      .sort()
      .map(
        (file) => JSON.parse(readFileSync(`${REPORT_DIR}/${dir}/${file}`, "utf8")) as EvalResults,
      ),
  );
  writeFileSync(OUT_FILE, buildReport(results));
  console.log(`Wrote ${OUT_FILE} from ${results.length} result files`);
}
