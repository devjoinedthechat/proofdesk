import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import type { EvalResults, RunRecord } from "./eval-run.ts";

// Turns the JSON files written by the eval runner into the tables of the
// eval report. Run it with: pnpm evals:report

const DATA_DIR = fileURLToPath(new URL("../../../docs/eval-report/data", import.meta.url));
const OUT_FILE = fileURLToPath(new URL("../../../docs/eval-report/results.md", import.meta.url));

/** What went wrong in a failed attempt, most serious first. */
export const FAILURE_KINDS = [
  ["wrong_money", "Money moved wrongly, or did not move when it should have"],
  ["wrong_approval", "Approval requested when not needed, or not requested when needed"],
  ["did_not_finish", "The agent did not reach a resolution"],
  ["guard_stopped", "The guard stopped the reply because it did not match the actions"],
  ["wrong_outcome", "Final state correct, but the stated outcome was wrong"],
  ["wrong_reason", "Outcome correct, but the reason code was wrong"],
  ["reply", "Reply left out a required fact or included a forbidden one"],
  ["error", "The run failed with an error"],
] as const;

export type FailureKind = (typeof FAILURE_KINDS)[number][0];

export function classify(run: RunRecord): FailureKind | null {
  if (run.passed) return null;
  const has = (prefix: string) => run.failures.some((failure) => failure.startsWith(prefix));
  if (run.error || has("solver threw") || has("run error")) return "error";
  if (has("refunds:") || has("unexpected change")) return "wrong_money";
  if (has("approvals:")) return "wrong_approval";
  if (run.actual?.reasonCode.startsWith("agent_")) return "did_not_finish";
  if (run.actual?.reasonCode.startsWith("guard_")) return "guard_stopped";
  if (has("outcome:")) return "wrong_outcome";
  if (has("reason:")) return "wrong_reason";
  return "reply";
}

const dollars = (micros: number, digits = 4) => `$${(micros / 1_000_000).toFixed(digits)}`;
const percent = (part: number, whole: number) =>
  whole === 0 ? "n/a" : `${((100 * part) / whole).toFixed(1)}%`;
const seconds = (ms: number) => `${(ms / 1000).toFixed(1)} s`;

function quantile(values: number[], q: number): number {
  const sorted = [...values].sort((a, b) => a - b);
  if (sorted.length === 0) return 0;
  return sorted[Math.min(sorted.length - 1, Math.ceil(q * sorted.length) - 1)] ?? 0;
}
const mean = (values: number[]) =>
  values.length ? values.reduce((a, b) => a + b, 0) / values.length : 0;

function table(header: string[], rows: string[][]): string {
  return [
    `| ${header.join(" | ")} |`,
    `| ${header.map(() => "---").join(" | ")} |`,
    ...rows.map((row) => `| ${row.join(" | ")} |`),
  ].join("\n");
}

export function buildReport(results: EvalResults[]): string {
  const sections: string[] = [
    "# Eval results",
    "Generated by `pnpm evals:report` from the files in `data/`. Do not edit by hand.",
  ];

  sections.push(
    "## Summary",
    table(
      [
        "Run",
        "Model",
        "Effort",
        "Prompt",
        "Attempts",
        "Passed",
        "Pass rate per repeat",
        "Cost per ticket (mean / p95)",
        "Time per ticket (p50 / p95)",
        "Model calls per ticket",
        "Total cost",
      ],
      results.map((result) => {
        const perRepeat = Array.from({ length: result.repeats }, (_, index) => {
          const runs = result.runs.filter((run) => run.repeat === index + 1);
          return runs.length ? percent(runs.filter((run) => run.passed).length, runs.length) : null;
        }).filter(Boolean);
        const costs = result.runs.map((run) => run.costMicros);
        const times = result.runs.map((run) => run.latencyMs);
        return [
          result.label,
          `\`${result.model}\``,
          result.effort,
          result.prompt,
          String(result.runs.length),
          `${result.runs.filter((run) => run.passed).length} (${percent(result.runs.filter((run) => run.passed).length, result.runs.length)})`,
          perRepeat.join(", "),
          `${dollars(mean(costs))} / ${dollars(quantile(costs, 0.95))}`,
          `${seconds(quantile(times, 0.5))} / ${seconds(quantile(times, 0.95))}`,
          mean(result.runs.map((run) => run.modelCalls)).toFixed(1),
          `${dollars(result.totalCostMicros, 2)}${result.stoppedAtSpendCap ? " (stopped at cap)" : ""}`,
        ];
      }),
    ),
  );

  sections.push(
    "## Consistency",
    "How many scenarios passed on every repeat, on some, and on none.",
    table(
      ["Run", "Always passed", "Sometimes passed", "Never passed"],
      results.map((result) => {
        const byScenario = new Map<string, boolean[]>();
        for (const run of result.runs) {
          byScenario.set(run.scenario, [...(byScenario.get(run.scenario) ?? []), run.passed]);
        }
        const groups = [...byScenario.values()];
        return [
          result.label,
          String(groups.filter((group) => group.every(Boolean)).length),
          String(groups.filter((group) => group.some(Boolean) && !group.every(Boolean)).length),
          String(groups.filter((group) => !group.some(Boolean)).length),
        ];
      }),
    ),
  );

  sections.push(
    "## Failures by kind",
    table(
      ["Kind", ...results.map((result) => result.label)],
      FAILURE_KINDS.map(([kind, description]) => [
        description,
        ...results.map((result) =>
          String(result.runs.filter((run) => classify(run) === kind).length),
        ),
      ]),
    ),
  );

  const scenarioIds = [
    ...new Set(results.flatMap((result) => result.runs.map((run) => run.scenario))),
  ].sort();
  sections.push(
    "## Per scenario",
    "Attempts passed out of attempts made.",
    table(
      ["Scenario", ...results.map((result) => result.label)],
      scenarioIds.map((id) => [
        `\`${id}\``,
        ...results.map((result) => {
          const runs = result.runs.filter((run) => run.scenario === id);
          return runs.length ? `${runs.filter((run) => run.passed).length}/${runs.length}` : "";
        }),
      ]),
    ),
  );

  const failed = results.flatMap((result) =>
    result.runs.filter((run) => !run.passed).map((run) => ({ label: result.label, run })),
  );
  if (failed.length > 0) {
    sections.push(
      "## Every failed attempt",
      table(
        ["Run", "Scenario", "Repeat", "Kind", "Expected", "Got", "Differences"],
        failed.map(({ label, run }) => [
          label,
          `\`${run.scenario}\``,
          String(run.repeat),
          classify(run) ?? "",
          `${run.expected.outcome} / ${run.expected.reasonCode}`,
          run.actual ? `${run.actual.outcome} / ${run.actual.reasonCode}` : "none",
          run.failures.join("; ").replaceAll("|", "\\|"),
        ]),
      ),
    );
  }

  return `${sections.join("\n\n")}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const results = readdirSync(DATA_DIR)
    .filter((file) => file.endsWith(".json"))
    .sort()
    .map((file) => JSON.parse(readFileSync(`${DATA_DIR}/${file}`, "utf8")) as EvalResults);
  writeFileSync(OUT_FILE, buildReport(results));
  console.log(`Wrote ${OUT_FILE} from ${results.length} result files`);
}
